Q = []  # {category, type, question, options, answer, explanation}

def add(category, qtype, question, options, answer, explanation):
    Q.append({
        "category": category,
        "type": qtype,
        "question": question,
        "options": options,
        "answer": answer,
        "explanation": explanation,
    })

def single(cat, q, correct, *rest):
    # rest = [w1, w2, w3, expl] 或 [w1, w2, expl] 或 ([w1,w2,w3], expl)
    if len(rest) == 2 and isinstance(rest[0], list):
        wrongs, expl = rest[0], rest[1]
    else:
        expl = rest[-1]
        wrongs = list(rest[:-1])
        if len(wrongs) < 3:
            wrongs = wrongs + ["以上都不是", "以上都正确", "无法确定"][: 3 - len(wrongs)]
        wrongs = wrongs[:3]
    opts = [correct] + wrongs
    random.shuffle(opts)
    add(cat, "single", q, opts, opts.index(correct), expl)

def judge(cat, q, is_true, expl_true, expl_false=""):
    add(cat, "judge", q, ["正确", "错误"], 0 if is_true else 1,
        expl_true if is_true else (expl_false or expl_true))

